import asyncio
from json import JSONDecodeError
from json import loads as json_loads
from pathlib import Path
from typing import Any

from typing_extensions import override

from ..model import YandexResponse
from ..network import RESP
from ..utils import deep_get, parse_html, read_file
from .base import BaseSearchEngine


class Yandex(BaseSearchEngine[YandexResponse]):
    """API client for the Yandex reverse image search engine.

    This class provides an interface to perform reverse image searches using Yandex's service.
    It supports searching by both image URL and local image file upload.

    Attributes:
        base_url (str): The base URL for Yandex image search service.
        ai_overview (bool): Whether to load the AI overview generated by Yandex Neuro.
        q (Optional[str]): Optional question about the image for the AI overview.

    Note:
        - The service might be affected by regional restrictions.
        - Search results may vary based on the user's location and Yandex's algorithms.
        - Yandex limits AI overview requests to about 100 per hour.
    """

    def __init__(
        self,
        base_url: str = "https://yandex.com",
        ai_overview: bool = False,
        q: str | None = None,
        **request_kwargs: Any,
    ):
        """Initializes a Yandex API client with specified configurations.

        Args:
            base_url (str): The base URL for Yandex searches.
            ai_overview (bool): If True, load the AI overview with extra requests. Defaults to False.
            q (Optional[str]): Optional question about the image for the AI overview. Defaults to None.
            **request_kwargs (Any): Additional arguments for network requests.
        """
        base_url = f"{base_url}/images/search"
        super().__init__(base_url, **request_kwargs)
        self.ai_overview: bool = ai_overview
        self.q: str | None = q

    async def _get_ai_overview(self, resp: RESP, q: str | None = None) -> dict[str, Any] | None:
        """Requests the AI overview for the searched image and waits until it is generated.

        Args:
            resp (RESP): Response of the search results page.
            q (Optional[str]): Optional question about the image.

        Returns:
            Optional[dict[str, Any]]: The generated AI overview data, or None if it is not available.
        """
        data_state = parse_html(resp.text)('div.Root[id^="ImagesApp-"]').attr("data-state")
        state = json_loads(str(data_state)) if data_state else {}
        api_url = deep_get(state, "initialState.cbirFuturisSearch.futurisBackendURL")
        cbir_id = deep_get(state, "initialState.cbirPreview.cbirId")
        if not (api_url and cbir_id):
            return None

        api, _, query = api_url.partition("?")

        async def post(endpoint: str, data: dict[str, Any]) -> dict[str, Any]:
            resp = await self._send_request(method="post", url=f"{api}/{endpoint}?{query}", json=data)
            try:
                return json_loads(resp.text)
            except JSONDecodeError:
                return {}

        message = await post("send_to_dialog", {"UserRequest": q or "", "CbirId": cbir_id})
        if not (message_id := message.get("ResponseMessageId")):
            return None

        for _ in range(20):
            await asyncio.sleep(0.5)
            data = await post("get_fresh_message", {"ResponseMessageId": message_id})
            if data.get("IsCompleteResults"):
                return data
        return None

    @override
    async def search(
        self,
        url: str | None = None,
        file: str | bytes | Path | None = None,
        q: str | None = None,
        **kwargs: Any,
    ) -> YandexResponse:
        """Performs a reverse image search on Yandex.

        This method supports two ways of searching:
            1. Search by image URL
            2. Search by uploading a local image file

        Args:
            url (Optional[str]): URL of the image to search.
            file (Union[str, bytes, Path, None]): Local image file, can be a path string, bytes data, or Path object.
            q (Optional[str]): Optional question about the image for the AI overview. Overrides the instance's q
                attribute if provided.
            **kwargs (Any): Additional arguments passed to the parent class.

        Returns:
            YandexResponse: An object containing:
                - Search results and metadata
                - The final search URL used by Yandex

        Raises:
            ValueError: If neither `url` nor `file` is provided.

        Note:
            - Only one of `url` or `file` should be provided.
            - When using file upload, the image will be sent to Yandex's servers.
            - The search process involves standard Yandex parameters like `rpt` and `cbir_page`.
        """
        params = {"rpt": "imageview", "cbir_page": "sites"}

        if url:
            params["url"] = url
            resp = await self._send_request(method="get", params=params)
        elif file:
            files = {"upfile": read_file(file)}
            resp = await self._send_request(
                method="post",
                params=params,
                data={"prg": 1},
                files=files,
            )
        else:
            raise ValueError("Either 'url' or 'file' must be provided")

        ai_overview = await self._get_ai_overview(resp, q if q is not None else self.q) if self.ai_overview else None
        return YandexResponse(resp.text, resp.url, ai_overview=ai_overview)
